const fs = require("fs");
const path = require("path");
const {
  collectDeclaredDependencies,
  getPackageNameFromSpecifier,
  isNodeBuiltinPackage,
  readPackageManifest
} = require("./frontend-package-manager");

const HTML_EXTENSIONS = new Set([".html", ".htm"]);
const STYLE_EXTENSIONS = [".css", ".scss", ".sass", ".less"];
const SCRIPT_EXTENSIONS = [".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx"];
const CREATABLE_EXTENSIONS = new Map([
  [".css", "/* Auto-generated by Code Janitor */\n"],
  [".scss", "/* Auto-generated by Code Janitor */\n"],
  [".sass", "/* Auto-generated by Code Janitor */\n"],
  [".less", "/* Auto-generated by Code Janitor */\n"],
  [".js", "// Auto-generated by Code Janitor\n"],
  [".jsx", "// Auto-generated by Code Janitor\n"],
  [".mjs", "export {};\n"],
  [".cjs", "module.exports = {};\n"],
  [".ts", "export {};\n"],
  [".tsx", "// Auto-generated by Code Janitor\n"],
  [".json", "{}\n"],
  [".webmanifest", "{\n  \"name\": \"\",\n  \"short_name\": \"\"\n}\n"],
  [
    ".html",
    "<!DOCTYPE html>\n<html>\n<head>\n  <meta charset=\"UTF-8\" />\n  <title></title>\n</head>\n<body>\n</body>\n</html>\n"
  ],
  [
    ".htm",
    "<!DOCTYPE html>\n<html>\n<head>\n  <meta charset=\"UTF-8\" />\n  <title></title>\n</head>\n<body>\n</body>\n</html>\n"
  ]
]);

class FrontendValidator {
  constructor(filePath, code, options = {}) {
    this.filePath = filePath;
    this.code = code;
    this.workspaceRoot = this._getWorkspaceRoot();
    this.packageManifest = readPackageManifest(this.workspaceRoot);
    this.declaredPackages = collectDeclaredDependencies(this.packageManifest);
    this.pathAliases = this._loadPathAliases();
    this.graphData = options.graphData || null;
    this.graphRoot = options.graphRoot
      ? path.resolve(options.graphRoot)
      : this.workspaceRoot;
    this.graphPathLookup = this._buildGraphPathLookup(this.graphData);
    this.graphFilePath = this.graphRoot
      ? this._normalizeGraphPath(path.relative(this.graphRoot, this.filePath))
      : "";
    this.issues = [];
    this.issueKeys = new Set();
  }

  _getWorkspaceRoot() {
    let dir = path.dirname(this.filePath);
    while (dir !== path.dirname(dir)) {
      if (
        fs.existsSync(path.join(dir, "package.json")) ||
        fs.existsSync(path.join(dir, ".git"))
      ) {
        return dir;
      }
      dir = path.dirname(dir);
    }
    return path.dirname(this.filePath);
  }

  validate() {
    this.issues = [];
    this.issueKeys = new Set();

    const ext = path.extname(this.filePath).toLowerCase();

    if (HTML_EXTENSIONS.has(ext)) {
      this._validateHTML();
    } else if (STYLE_EXTENSIONS.includes(ext)) {
      this._validateCSS();
    } else if (SCRIPT_EXTENSIONS.includes(ext)) {
      this._validateJS();
    }

    return {
      hasIssues: this.issues.length > 0,
      issues: [...this.issues],
      fixedCode: this.code,
      graphContextUsed: !!this.graphPathLookup
    };
  }

  createMissingFiles(issues = this.issues) {
    const createdFiles = [];
    const skipped = [];
    const seenPaths = new Set();

    for (const issue of issues) {
      if (
        issue.type !== "missing-file" ||
        !issue.creatable ||
        !issue.resolvedPath ||
        seenPaths.has(issue.resolvedPath)
      ) {
        continue;
      }

      seenPaths.add(issue.resolvedPath);

      if (!this._isPathWithinWorkspace(issue.resolvedPath)) {
        skipped.push(issue);
        continue;
      }

      const dir = path.dirname(issue.resolvedPath);
      fs.mkdirSync(dir, { recursive: true });

      if (!fs.existsSync(issue.resolvedPath)) {
        fs.writeFileSync(
          issue.resolvedPath,
          this._getPlaceholderContent(issue.resolvedPath),
          "utf8"
        );
        createdFiles.push(issue.resolvedPath);
      }
    }

    return {
      createdFiles,
      skipped
    };
  }

  _validateHTML() {
    this._scanAttributeReferences(
      /<link\b[^>]*href\s*=\s*["']([^"']+)["'][^>]*>/gi,
      (match, href) => {
        if (!this._shouldValidateLinkTag(match[0], href)) return null;
        return {
          kind: this._inferLinkKind(match[0], href),
          message: `Linked resource not found: ${href}`
        };
      }
    );

    this._scanAttributeReferences(
      /<script\b[^>]*src\s*=\s*["']([^"']+)["'][^>]*>/gi,
      () => ({
        kind: "script",
        message: "Script file not found"
      })
    );

    this._scanAttributeReferences(
      /<(?:img|audio|video|source|track)\b[^>]*src\s*=\s*["']([^"']+)["'][^>]*>/gi,
      () => ({
        kind: "asset",
        message: "Asset file not found"
      })
    );

    this._scanAttributeReferences(
      /<video\b[^>]*poster\s*=\s*["']([^"']+)["'][^>]*>/gi,
      () => ({
        kind: "asset",
        message: "Poster image not found"
      })
    );

    this._scanSrcSetReferences(
      /\bsrcset\s*=\s*["']([^"']+)["']/gi,
      "Asset file in srcset not found"
    );
  }

  _validateCSS() {
    this._scanAttributeReferences(
      /@import\s+(?:url\(\s*)?["']([^"']+)["']\s*\)?/gi,
      () => ({
        kind: "stylesheet",
        message: "CSS import not found"
      })
    );

    this._scanAttributeReferences(
      /url\(\s*["']?([^"')]+)["']?\s*\)/gi,
      () => ({
        kind: "asset",
        message: "Referenced asset not found"
      })
    );
  }

  _validateJS() {
    this._scanAttributeReferences(
      /import\s+[\s\S]*?\sfrom\s+["']([^"']+)["']/gi,
      (match, specifier) => this._buildJSImportDescriptor(
        specifier,
        `Module not found: ${specifier}`,
        "Package dependency not found in package.json"
      )
    );

    this._scanAttributeReferences(
      /export\s+[\s\S]*?\sfrom\s+["']([^"']+)["']/gi,
      (match, specifier) => this._buildJSImportDescriptor(
        specifier,
        `Re-export target not found: ${specifier}`,
        "Package dependency not found in package.json"
      )
    );

    this._scanAttributeReferences(
      /import\s*["']([^"']+)["']/gi,
      (match, specifier) => this._buildJSImportDescriptor(
        specifier,
        `Imported module not found: ${specifier}`,
        "Package dependency not found in package.json"
      )
    );

    this._scanAttributeReferences(
      /require\(\s*["']([^"']+)["']\s*\)/gi,
      (match, specifier) => this._buildJSImportDescriptor(
        specifier,
        `Required module not found: ${specifier}`,
        "Package dependency not found in package.json"
      )
    );

    this._scanAttributeReferences(
      /import\(\s*["']([^"']+)["']\s*\)/gi,
      (match, specifier) => this._buildJSImportDescriptor(
        specifier,
        `Dynamic import target not found: ${specifier}`,
        "Package dependency not found in package.json"
      )
    );

    this._scanAttributeReferences(
      /new\s+URL\(\s*["']([^"']+)["']\s*,\s*import\.meta\.url\s*\)/gi,
      (match, specifier) =>
        this._shouldValidateModuleSpecifier(specifier)
          ? {
              kind: "asset",
              message: `Referenced asset not found: ${specifier}`
            }
          : null
    );
  }

  _scanAttributeReferences(regex, buildIssue) {
    let match = regex.exec(this.code);
    while (match) {
      const fullMatch = match[0];
      const reference = (match[1] || "").trim();
      const descriptor = buildIssue(match, reference);

      if (descriptor && reference) {
        const relativeIndex = Math.max(fullMatch.indexOf(reference), 0);
        const absoluteIndex = match.index + relativeIndex;
        if (descriptor.issueType === "missing-package") {
          this._addMissingPackage({
            index: absoluteIndex,
            specifier: reference,
            message: descriptor.message
          });
        } else {
          this._addMissingReference({
            index: absoluteIndex,
            reference,
            kind: descriptor.kind,
            message: descriptor.message
          });
        }
      }

      match = regex.exec(this.code);
    }
  }

  _scanSrcSetReferences(regex, message) {
    let match = regex.exec(this.code);
    while (match) {
      const srcsetValue = match[1] || "";
      const captureIndex = match.index + match[0].indexOf(srcsetValue);
      const entries = srcsetValue
        .split(",")
        .map((part) => part.trim())
        .filter(Boolean);

      let searchOffset = 0;
      for (const entry of entries) {
        const reference = entry.split(/\s+/)[0];
        if (!reference) continue;

        const entryIndex = srcsetValue.indexOf(reference, searchOffset);
        searchOffset = entryIndex + reference.length;

        this._addMissingReference({
          index: captureIndex + Math.max(entryIndex, 0),
          reference,
          kind: "asset",
          message: `${message}: ${reference}`
        });
      }

      match = regex.exec(this.code);
    }
  }

  _addMissingReference({ index, reference, kind, message }) {
    if (this._shouldIgnoreSpecifier(reference)) {
      return;
    }

    const resolution = this._resolveDependencyPath(reference, kind);
    if (resolution.exists) {
      return;
    }

    const location = this._getLocation(index, reference.length);
    const issue = {
      type: "missing-file",
      file: reference,
      normalizedFile: resolution.normalizedSpecifier,
      resolvedPath: resolution.resolvedPath,
      line: location.line,
      column: location.column,
      length: location.length,
      kind,
      message: message.includes(reference) ? message : `${message}: ${reference}`,
      creatable: this._isCreatableResource(resolution.resolvedPath, kind)
    };

    const issueKey = `${issue.resolvedPath}|${issue.line}|${issue.column}|${issue.message}`;
    if (this.issueKeys.has(issueKey)) {
      return;
    }

    this.issueKeys.add(issueKey);
    this.issues.push(issue);
  }

  _addMissingPackage({ index, specifier, message }) {
    if (!this.packageManifest) {
      return;
    }

    const packageName = getPackageNameFromSpecifier(specifier);
    if (
      !packageName ||
      this.declaredPackages.has(packageName) ||
      isNodeBuiltinPackage(packageName) ||
      this._isPathAliasSpecifier(specifier)
    ) {
      return;
    }

    const location = this._getLocation(index, specifier.length);
    const issue = {
      type: "missing-package",
      file: specifier,
      packageName,
      workspaceRoot: this.workspaceRoot,
      line: location.line,
      column: location.column,
      length: location.length,
      kind: "package",
      message: message.includes(packageName)
        ? message
        : `${message}: ${packageName}`,
      creatable: false,
      installable: true
    };

    const issueKey = `${issue.type}|${issue.packageName}|${issue.line}|${issue.column}`;
    if (this.issueKeys.has(issueKey)) {
      return;
    }

    this.issueKeys.add(issueKey);
    this.issues.push(issue);
  }

  _buildJSImportDescriptor(specifier, localMessage, packageMessage) {
    if (this._shouldValidateModuleSpecifier(specifier)) {
      return {
        kind: "module",
        message: localMessage
      };
    }

    if (this._shouldValidatePackageSpecifier(specifier)) {
      return {
        issueType: "missing-package",
        kind: "package",
        message: packageMessage
      };
    }

    return null;
  }

  _shouldValidateLinkTag(tagText, href) {
    if (this._shouldIgnoreSpecifier(href)) {
      return false;
    }

    const relMatch = tagText.match(/\brel\s*=\s*["']([^"']+)["']/i);
    const rel = relMatch ? relMatch[1].toLowerCase() : "";

    if (
      /stylesheet|icon|manifest|preload|modulepreload|prefetch|apple-touch-icon/.test(
        rel
      )
    ) {
      return true;
    }

    return /\.(css|scss|sass|less|json|webmanifest|svg|png|jpe?g|gif|webp|avif)$/i.test(
      this._stripQueryAndHash(href)
    );
  }

  _inferLinkKind(tagText, href) {
    const relMatch = tagText.match(/\brel\s*=\s*["']([^"']+)["']/i);
    const rel = relMatch ? relMatch[1].toLowerCase() : "";
    const normalized = this._stripQueryAndHash(href).toLowerCase();
    return /stylesheet|modulepreload/.test(rel) ||
      STYLE_EXTENSIONS.some((ext) => normalized.endsWith(ext))
      ? "stylesheet"
      : "asset";
  }

  _shouldValidateModuleSpecifier(specifier) {
    return (
      !!specifier &&
      !this._shouldIgnoreSpecifier(specifier) &&
      (/^\.\.?\//.test(specifier) || specifier.startsWith("/"))
    );
  }

  _shouldValidatePackageSpecifier(specifier) {
    return (
      !!specifier &&
      !!this.packageManifest &&
      !this._shouldIgnoreSpecifier(specifier) &&
      !/^\.\.?\//.test(specifier) &&
      !specifier.startsWith("/") &&
      !specifier.startsWith("\\") &&
      !this._isPathAliasSpecifier(specifier)
    );
  }

  _shouldIgnoreSpecifier(specifier) {
    const trimmed = (specifier || "").trim();
    if (!trimmed) return true;

    return (
      /^__[\w.-]+__$/.test(trimmed) ||
      /^\$\{[^}]+\}$/.test(trimmed) ||
      /^\{\{[\s\S]+\}\}$/.test(trimmed) ||
      /^<%[-=]?[\s\S]+%>$/.test(trimmed) ||
      trimmed.startsWith("#") ||
      /^data:/i.test(trimmed) ||
      /^blob:/i.test(trimmed) ||
      /^about:/i.test(trimmed) ||
      /^mailto:/i.test(trimmed) ||
      /^tel:/i.test(trimmed) ||
      /^javascript:/i.test(trimmed) ||
      /^https?:/i.test(trimmed) ||
      /^\/\//.test(trimmed)
    );
  }

  _resolveDependencyPath(specifier, kind) {
    const normalizedSpecifier = this._stripQueryAndHash(specifier);
    const baseDir = path.dirname(this.filePath);
    const isRootRelative =
      /^[\\/]/.test(normalizedSpecifier) &&
      !/^[a-zA-Z]:[\\/]/.test(normalizedSpecifier) &&
      !normalizedSpecifier.startsWith("//") &&
      !normalizedSpecifier.startsWith("\\\\");

    const basePath = isRootRelative
      ? path.join(this.workspaceRoot, normalizedSpecifier.replace(/^[\\/]+/, ""))
      : path.resolve(baseDir, normalizedSpecifier);
    const candidateBases = [basePath];
    const workspaceRelativePath = this._getWorkspaceRelativeFallbackPath(
      normalizedSpecifier,
      kind
    );
    if (workspaceRelativePath && workspaceRelativePath !== basePath) {
      candidateBases.push(workspaceRelativePath);
    }
    const graphResolvedPath = this._getGraphResolvedPath(
      normalizedSpecifier,
      kind
    );
    if (graphResolvedPath && !candidateBases.includes(graphResolvedPath)) {
      candidateBases.push(graphResolvedPath);
    }

    const ext = path.extname(basePath).toLowerCase();

    const candidates = [];
    let creatablePath = basePath;

    candidateBases.forEach((candidateBase) => {
      candidates.push(candidateBase);
    });

    if (!ext) {
      if (kind === "module" || kind === "script") {
        candidateBases.forEach((candidateBase) => {
          for (const candidateExt of SCRIPT_EXTENSIONS) {
            candidates.push(candidateBase + candidateExt);
            candidates.push(path.join(candidateBase, "index" + candidateExt));
          }
        });
        creatablePath = basePath + ".js";
      } else if (kind === "stylesheet") {
        candidateBases.forEach((candidateBase) => {
          for (const candidateExt of STYLE_EXTENSIONS) {
            candidates.push(candidateBase + candidateExt);
            candidates.push(path.join(candidateBase, "index" + candidateExt));
          }
        });
        creatablePath = basePath + ".css";
      }
    }

    const existingPath = candidates.find((candidate) => fs.existsSync(candidate));

    return {
      exists: !!existingPath,
      normalizedSpecifier,
      resolvedPath: existingPath || creatablePath
    };
  }

  _stripQueryAndHash(specifier) {
    return (specifier || "").trim().replace(/[?#].*$/, "");
  }

  _getWorkspaceRelativeFallbackPath(specifier, kind) {
    if (!this.workspaceRoot || !specifier) {
      return null;
    }

    if (!["asset", "stylesheet", "script"].includes(kind)) {
      return null;
    }

    if (
      /^[\\/]/.test(specifier) ||
      /^[a-zA-Z]:[\\/]/.test(specifier) ||
      specifier.startsWith("//") ||
      specifier.startsWith("\\\\") ||
      /^\.\.?(?:[\\/]|$)/.test(specifier) ||
      !/[\\/]/.test(specifier)
    ) {
      return null;
    }

    return path.join(this.workspaceRoot, specifier.replace(/^[\\/]+/, ""));
  }

  _buildGraphPathLookup(graphData) {
    const nodes = Array.isArray(graphData?.nodes) ? graphData.nodes : [];
    if (nodes.length === 0) {
      return null;
    }

    const lookup = new Set();
    nodes.forEach((node) => {
      const normalizedPath = this._normalizeGraphPath(node?.path);
      if (normalizedPath) {
        lookup.add(normalizedPath);
      }
    });

    return lookup.size > 0 ? lookup : null;
  }

  _normalizeGraphPath(targetPath) {
    const normalized = String(targetPath || "")
      .trim()
      .replace(/\\/g, "/");
    if (!normalized) {
      return "";
    }

    const cleaned = path.posix.normalize(normalized).replace(/^\/+/, "");
    return cleaned === "." ? "" : cleaned.replace(/^(?:\.\/)+/, "");
  }

  _getGraphResolvedPath(specifier, kind) {
    if (!this.graphPathLookup || !this.graphRoot) {
      return null;
    }

    const matchedPath = this._buildGraphSpecifierCandidates(specifier, kind).find(
      (candidate) => this.graphPathLookup.has(candidate)
    );
    return matchedPath ? path.join(this.graphRoot, matchedPath) : null;
  }

  _buildGraphSpecifierCandidates(specifier, kind) {
    const normalizedSpecifier = this._normalizeGraphPath(
      this._stripQueryAndHash(specifier)
    );
    if (!normalizedSpecifier) {
      return [];
    }

    const candidates = new Set();
    const isRelative = /^\.\.?(?:\/|$)/.test(normalizedSpecifier);

    if (isRelative && this.graphFilePath) {
      candidates.add(
        this._normalizeGraphPath(
          path.posix.join(path.posix.dirname(this.graphFilePath), normalizedSpecifier)
        )
      );
    } else {
      candidates.add(normalizedSpecifier);
    }

    if (
      !isRelative &&
      !/^[a-zA-Z]:\//.test(normalizedSpecifier) &&
      !normalizedSpecifier.startsWith("//")
    ) {
      candidates.add(normalizedSpecifier.replace(/^\/+/, ""));
    }

    if (!path.posix.extname(normalizedSpecifier)) {
      const candidateExts =
        kind === "stylesheet"
          ? STYLE_EXTENSIONS
          : kind === "module" || kind === "script"
            ? SCRIPT_EXTENSIONS
            : [];

      candidateExts.forEach((candidateExt) => {
        Array.from(candidates).forEach((candidate) => {
          candidates.add(candidate + candidateExt);
          candidates.add(
            this._normalizeGraphPath(path.posix.join(candidate, "index" + candidateExt))
          );
        });
      });
    }

    return Array.from(candidates).filter(Boolean);
  }

  _getLocation(index, length = 1) {
    const safeIndex = Math.max(index, 0);
    const beforeText = this.code.slice(0, safeIndex);
    const lines = beforeText.split("\n");

    return {
      line: lines.length,
      column: lines[lines.length - 1].length + 1,
      length: Math.max(length, 1)
    };
  }

  _isCreatableResource(resolvedPath, kind) {
    if (!resolvedPath || !this._isPathWithinWorkspace(resolvedPath)) {
      return false;
    }

    const ext = path.extname(resolvedPath).toLowerCase();
    if (CREATABLE_EXTENSIONS.has(ext)) {
      return true;
    }

    return !ext && (kind === "module" || kind === "script" || kind === "stylesheet");
  }

  _isPathWithinWorkspace(targetPath) {
    const root = this.workspaceRoot || path.dirname(this.filePath);
    const relative = path.relative(root, targetPath);
    return relative === "" || (!relative.startsWith("..") && !path.isAbsolute(relative));
  }

  _getPlaceholderContent(targetPath) {
    const ext = path.extname(targetPath).toLowerCase();
    return CREATABLE_EXTENSIONS.get(ext) || "";
  }

  _loadPathAliases() {
    const aliases = [];
    const configFiles = ["tsconfig.json", "jsconfig.json"];

    for (const fileName of configFiles) {
      const configPath = path.join(this.workspaceRoot, fileName);
      const config = this._readJsonConfigFile(configPath);
      const paths = config?.compilerOptions?.paths;

      if (!paths || typeof paths !== "object") {
        continue;
      }

      Object.keys(paths).forEach((alias) => {
        if (alias.endsWith("/*")) {
          aliases.push({ type: "prefix", value: alias.slice(0, -1) });
        } else {
          aliases.push({ type: "exact", value: alias });
        }
      });
    }

    return aliases;
  }

  _isPathAliasSpecifier(specifier) {
    if (!specifier) {
      return false;
    }

    if (specifier.startsWith("@/") || specifier.startsWith("~/")) {
      return true;
    }

    return this.pathAliases.some((alias) =>
      alias.type === "prefix"
        ? specifier.startsWith(alias.value)
        : specifier === alias.value
    );
  }

  _readJsonConfigFile(filePath) {
    if (!fs.existsSync(filePath)) {
      return null;
    }

    try {
      const raw = fs.readFileSync(filePath, "utf8");
      const cleaned = raw
        .replace(/\/\*[\s\S]*?\*\//g, "")
        .replace(/^\s*\/\/.*$/gm, "")
        .replace(/,\s*([}\]])/g, "$1");
      return JSON.parse(cleaned);
    } catch (error) {
      return null;
    }
  }
}

module.exports = FrontendValidator;
